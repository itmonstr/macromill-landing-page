begin;

create table if not exists public.landing_sessions (
  session_id uuid primary key,
  visitor_id uuid not null,
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  first_path text not null default '/',
  last_path text not null default '/',
  referrer text,
  source text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  device_type text,
  status text not null default 'active' check (status in ('active', 'converted')),
  max_stage smallint not null default 1 check (max_stage between 1 and 8),
  last_event text not null default 'landing_view',
  configuration jsonb not null default '{}'::jsonb,
  converted_at timestamptz
);

create table if not exists public.landing_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null unique,
  session_id uuid not null references public.landing_sessions(session_id) on delete cascade,
  event_name text not null,
  stage smallint not null check (stage between 1 and 8),
  path text not null default '/',
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.landing_leads (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null unique references public.landing_sessions(session_id) on delete restrict,
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  order_type text not null check (order_type in ('ration', 'custom_dishes')),
  tier text,
  goal text,
  days integer,
  meals_per_day text,
  total_text text,
  fulfillment_method text,
  destination text,
  first_date date,
  time_slot text,
  promo text,
  comment text,
  order_data jsonb not null default '{}'::jsonb,
  crm_status text not null default 'new' check (crm_status in ('new', 'contacted', 'confirmed', 'cancelled')),
  is_test boolean not null default false
);

create index if not exists landing_sessions_last_seen_idx
  on public.landing_sessions(last_seen_at desc);
create index if not exists landing_events_session_created_idx
  on public.landing_events(session_id, created_at);
create index if not exists landing_events_name_idx
  on public.landing_events(event_name, created_at desc);
create index if not exists landing_leads_created_idx
  on public.landing_leads(created_at desc);

alter table public.landing_sessions enable row level security;
alter table public.landing_events enable row level security;
alter table public.landing_leads enable row level security;

comment on table public.landing_sessions is 'Production landing funnel sessions.';
comment on table public.landing_events is 'Production landing funnel events; must not contain contact data.';
comment on table public.landing_leads is 'Production landing CRM leads.';

commit;

